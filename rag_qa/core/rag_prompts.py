def get_prompt(name: str) -> dict:
    """根据模板名称获取提示词。

    Args:
        name: 模板名称，如 "口语术语归一改写"

    Returns:
        {'name': str, 'category': str, 'system': str, 'user': str, 'needs_history': bool}
    """
    for p_name, category, system, user, needs_history in PROMPT_REGISTRY:
        if p_name == name:
            return {
                'name': p_name,
                'category': category,
                'system': system,
                'user': user,
                'needs_history': needs_history,
            }
    raise KeyError(f"未找到提示词模板: {name}")


def list_prompts() -> list:
    """列出所有可用模板名称。"""
    return [p[0] for p in PROMPT_REGISTRY]


def get_prompts_by_category(category: str) -> list:
    """按类别获取模板列表。"""
    return [p[0] for p in PROMPT_REGISTRY if p[1] == category]


def format_prompt(
    name: str,
    query: str,
    history: str = "",
    context: str = "",
) -> dict:
    """格式化提示词模板。

    Args:
        name:    模板名称
        query:   用户查询文本
        history: 对话历史（多轮场景），可选
        context: 检索到的参考文档内容（RAG 回答模板使用），可选

    Returns:
        {'system': str, 'user': str} 可直接传入 LLM 调用
    """
    info = get_prompt(name)
    user_prompt = info['user'].format(
        query=query,
        history=history or "无",
        context=context or "（暂无检索资料）",
    )
    return {
        'system': info['system'],
        'user': user_prompt,
    }


